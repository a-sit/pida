#!/usr/bin/env python3
"""Erzeugt das Demodokument der Apps (`apps/app/public/PIDA-Demo.pdf`, „Demo starten“).

Eine A4-Seite mit kurzem Text (Deutsch und Englisch) und einem QR-Platzhalter `PDF-AS-POS;id=1` ohne Profil, den PIDA
beim Öffnen erkennt; der Signaturblock landet dort. Der Platzhalter ist ein Bild wie beim Generator („QR-Platzhalter
erstellen“, 240 × 48 pt, QR links), weil die Erkennung Bilder dekodiert und die Bildbreite die Blockbreite bestimmt;
der Text daneben ist Vektortext darüber.

Deterministisch (keine Zeitstempel, feste /ID), ohne Fremdpakete.

Aufruf: make-demo-pdf.py tools/demo-qr-id1.txt apps/app/public/PIDA-Demo.pdf
  <qr-matrix-datei>: Module von `pida_placement::encode_qr("PDF-AS-POS;id=1")`, Zeilen aus 0/1
"""

import sys
import zlib

A4 = (595.28, 841.89)
MARGIN = 72
PLACEHOLDER = (240, 48)  # pt, wie crates/core-api/src/qr_placeholder.rs
MODULE_PX = 2  # Pixel je QR-Modul
QUIET = 2  # Ruhezone in Modulen


def num(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def text(s):
    """PDF-Zeichenkette in WinAnsi (Umlaute, Gedankenstrich)."""
    out = []
    for c in s:
        if c == "–":
            out.append("\\226")
        elif c in "()\\":
            out.append("\\" + c)
        elif ord(c) < 128:
            out.append(c)
        else:
            out.append(f"\\{ord(c.encode('cp1252')):03o}")
    return "(" + "".join(out) + ")"


def wrap(s, size, width):
    """Zeilenumbruch nach geschätzter Breite (Helvetica ≈ 0,5 em je Zeichen)."""
    words, lines, line = s.split(), [], ""
    for w in words:
        cand = f"{line} {w}".strip()
        if len(cand) * size * 0.5 > width and line:
            lines.append(line)
            line = w
        else:
            line = cand
    if line:
        lines.append(line)
    return lines


def placeholder_image(matrix):
    """Graustufenbild: QR mit Ruhezone links, rechts weiß (Seitenverhältnis 5 : 1)."""
    n = len(matrix)
    h = (n + 2 * QUIET) * MODULE_PX
    w = h * PLACEHOLDER[0] // PLACEHOLDER[1]
    rows = []
    for y in range(h):
        my = y // MODULE_PX - QUIET
        row = bytearray(b"\xff" * w)
        if 0 <= my < n:
            for x in range(n * MODULE_PX):
                if matrix[my][x // MODULE_PX] == "1":
                    row[QUIET * MODULE_PX + x] = 0
        rows.append(bytes(row))
    return w, h, b"".join(rows)


def build(matrix):
    pw, ph = A4
    width = pw - 2 * MARGIN
    ops = []
    y = ph - MARGIN - 24

    def para(s, font, size, gap):
        nonlocal y
        for line in wrap(s, size, width):
            ops.append(f"BT /{font} {size} Tf {num(MARGIN)} {num(y)} Td {text(line)} Tj ET")
            y -= size * 1.4
        y -= gap

    para("PIDA – Demodokument", "F2", 22, 6)
    para("Demo document", "F1", 14, 18)
    para(
        "Dieses Dokument liegt PIDA bei, damit Sie das Signieren gefahrlos ausprobieren können. Unten ist ein "
        "QR-Platzhalter eingefügt: PIDA erkennt ihn beim Öffnen und setzt den Signaturblock genau an diese Stelle.",
        "F1", 11, 8)
    para(
        "Sie können die Position im Arbeitsbereich ändern und das Dokument mit ID Austria tatsächlich signieren. "
        "Die Signatur ist echt, das Dokument selbst hat keinen rechtlich bedeutsamen Inhalt.",
        "F1", 11, 16)
    para(
        "This document ships with PIDA so you can try signing without risk. It contains a QR placeholder below: "
        "PIDA detects it when the document is opened and places the signature block exactly there.",
        "F1", 11, 8)
    para(
        "You can move the block in the workspace and really sign the document with ID Austria. The signature is "
        "genuine, but the document itself has no legally relevant content.",
        "F1", 11, 0)

    # Platzhalter im unteren Drittel, links bündig
    qx, qy = MARGIN, 220
    qw, qh = PLACEHOLDER
    ops.append(f"q {num(qw)} 0 0 {num(qh)} {num(qx)} {num(qy)} cm /Im1 Do Q")
    ops.append(f"0 G 0.75 w {num(qx + 0.375)} {num(qy + 0.375)} {num(qw - 0.75)} {num(qh - 0.75)} re S")
    tx = qx + qh + 4
    ops.append(f"BT /F1 8 Tf {num(tx)} {num(qy + 28)} Td {text('Platzhalter für die elektronische')} Tj ET")
    ops.append(f"BT /F1 8 Tf {num(tx)} {num(qy + 18)} Td {text('Signatur Nr. 1 – signature placeholder')} Tj ET")
    ops.append(f"BT /F1 8 Tf {num(tx)} {num(qy + 8)} Td {text('PIDA-Demo')} Tj ET")

    ops.append(f"BT /F1 8 Tf {num(MARGIN)} {num(MARGIN - 24)} Td "
               f"{text('Erzeugt mit tools/make-demo-pdf.py – generated by tools/make-demo-pdf.py')} Tj ET")
    content = ("\n".join(ops) + "\n").encode("latin-1")

    iw, ih, pixels = placeholder_image(matrix)
    objs = []

    def add(body):
        objs.append(body if isinstance(body, bytes) else body.encode("latin-1"))
        return len(objs)

    def stream(entries, data):
        data = zlib.compress(data, 9)
        return add(f"<< {entries} /Filter /FlateDecode /Length {len(data)} >>\nstream\n".encode("latin-1")
                   + data + b"\nendstream")

    f1 = add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>")
    f2 = add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>")
    im = stream(f"/Type /XObject /Subtype /Image /Width {iw} /Height {ih} /ColorSpace /DeviceGray "
                f"/BitsPerComponent 8 /Interpolate false", pixels)
    cs = stream("", content)
    pages = len(objs) + 2
    page = add(f"<< /Type /Page /Parent {pages} 0 R /MediaBox [0 0 {num(pw)} {num(ph)}] /Contents {cs} 0 R "
               f"/Resources << /Font << /F1 {f1} 0 R /F2 {f2} 0 R >> /XObject << /Im1 {im} 0 R >> >> >>")
    add(f"<< /Type /Pages /Kids [{page} 0 R] /Count 1 >>")
    info = add(f"<< /Title {text('PIDA – Demodokument')} /Producer (tools/make-demo-pdf.py) >>")
    root = add(f"<< /Type /Catalog /Pages {pages} 0 R /Lang (de-AT) >>")

    out = bytearray(b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for i, body in enumerate(objs, 1):
        offsets.append(len(out))
        out += f"{i} 0 obj\n".encode() + body + b"\nendobj\n"
    xref = len(out)
    out += f"xref\n0 {len(objs) + 1}\n0000000000 65535 f \n".encode()
    for o in offsets:
        out += f"{o:010d} 00000 n \n".encode()
    fid = "504944412044656d6f646f6b756d656e"
    out += (f"trailer\n<< /Size {len(objs) + 1} /Root {root} 0 R /Info {info} 0 R /ID [<{fid}> <{fid}>] >>\n"
            f"startxref\n{xref}\n%%EOF\n").encode()
    return bytes(out)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    matrix = [line.strip() for line in open(sys.argv[1], encoding="ascii") if line.strip()]
    assert matrix and all(set(r) <= {"0", "1"} and len(r) == len(matrix) for r in matrix), "QR-Matrix ungültig"
    with open(sys.argv[2], "wb") as f:
        f.write(build(matrix))


if __name__ == "__main__":
    main()
